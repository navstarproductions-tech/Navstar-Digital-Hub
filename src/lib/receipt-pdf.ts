export type NavstarReceiptData = {
  title?: string; serial: string; reference: string; payer: string; phone: string;
  amount: number; description: string; method?: string; mpesaCode: string;
  receivedAt: string; generatedAt?: string; status?: string;
};

const enc = (value: string) => value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^\x20-\x7E]/g, '-');
const pdfEscape = (value: string) => enc(value).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
const money = (value: number) => 'KSh ' + new Intl.NumberFormat('en-KE', { maximumFractionDigits: 0 }).format(value);

export function downloadNavstarReceipt(data: NavstarReceiptData) {
  const lines: string[] = [];
  const text = (x: number, y: number, size: number, value: string, color = '0.10 0.20 0.34') => {
    lines.push(`BT /F1 ${size} Tf ${color} rg 1 0 0 1 ${x} ${y} Tm (${pdfEscape(value)}) Tj ET`);
  };
  const rect = (x: number, y: number, w: number, h: number, fill: string, stroke?: string) => {
    lines.push(`${fill} rg ${x} ${y} ${w} ${h} re f`);
    if (stroke) lines.push(`${stroke} RG 0.8 w ${x} ${y} ${w} ${h} re S`);
  };
  const rule = (y: number, color = '0.82 0.87 0.92') => lines.push(`${color} RG 0.8 w 42 ${y} m 553 ${y} l S`);
  rect(0, 0, 595, 842, '1 1 1');
  rect(0, 650, 595, 192, '0.035 0.12 0.25');
  rect(0, 646, 595, 5, '0.91 0.72 0.29');
  text(42, 790, 22, 'NAVSTAR DIGITAL HUB', '1 1 1');
  text(42, 769, 10, 'HOME OF TECHNOCRATS', '0.98 0.85 0.48');
  text(42, 744, 9, '+254 797 688 576  |  +254 706 637 485', '0.88 0.93 1');
  text(42, 728, 9, 'navstardigitalhub@gmail.com  |  P.O. Box 546-50200, Bungoma, Kenya', '0.88 0.93 1');
  text(402, 790, 9, 'OFFICIAL DOCUMENT', '0.78 0.88 1');
  text(402, 769, 15, data.title || 'PAYMENT RECEIPT', '1 1 1');
  rect(402, 724, 151, 29, '1 0.94 0.94', '0.95 0.75 0.75');
  text(410, 735, 9, 'SERIAL: ' + data.serial, '0.65 0.12 0.16');
  text(42, 615, 11, 'PAYMENT RECEIVED  |  ' + (data.status || 'SAFARICOM CONFIRMED'), '0.08 0.48 0.30');
  text(42, 580, 9, 'RECEIVED FROM', '0.35 0.43 0.53');
  text(42, 559, 13, data.payer || 'Valued Customer');
  text(42, 540, 10, 'Phone: ' + data.phone);
  text(310, 580, 9, 'PAYMENT DETAILS', '0.35 0.43 0.53');
  text(310, 559, 11, data.method || 'Safaricom M-Pesa');
  text(310, 540, 9, 'Reference: ' + data.reference);
  text(310, 522, 9, 'M-Pesa code: ' + (data.mpesaCode || 'Not supplied'));
  text(42, 493, 9, 'DESCRIPTION', '0.35 0.43 0.53');
  text(42, 475, 11, data.description || 'Payment');
  rect(42, 385, 511, 65, '0.91 0.96 0.99', '0.70 0.82 0.93');
  text(60, 424, 9, 'AMOUNT RECEIVED', '0.14 0.31 0.48');
  text(60, 397, 23, money(data.amount), '0.04 0.39 0.31');
  text(42, 350, 9, 'DATE RECEIVED (EAT)', '0.35 0.43 0.53');
  text(42, 331, 11, data.receivedAt);
  text(310, 350, 9, 'DOCUMENT GENERATED (EAT)', '0.35 0.43 0.53');
  text(310, 331, 11, data.generatedAt || new Date().toLocaleString('en-KE', { timeZone: 'Africa/Nairobi' }));
  rule(300);
  text(42, 272, 11, 'PAYMENT CONFIRMATION');
  text(42, 251, 9, 'This receipt records a payment confirmed by the payment service provider.');
  text(42, 234, 9, 'The Navstar serial number is separate from the Safaricom transaction code.');
  rule(205, '0.05 0.27 0.52');
  text(42, 177, 12, 'Thank you for your payment.', '0.05 0.27 0.52');
  text(42, 157, 9, 'Electronically generated by Navstar Digital Hub. No physical signature required.');
  text(42, 139, 9, 'NAVSTAR DIGITAL HUB  |  HOME OF TECHNOCRATS', '0.05 0.27 0.52');
  text(42, 105, 8, 'Official digital receipt • Generated in East Africa Time (EAT)', '0.38 0.45 0.54');

  const stream = lines.join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    `<< /Length ${new TextEncoder().encode(stream).length} >>\nstream\n${stream}\nendstream`
  ];
  let output = '%PDF-1.4\n%NAVSTAR\n';
  const offsets = [0];
  for (let i = 0; i < objects.length; i++) {
    offsets.push(new TextEncoder().encode(output).length);
    output += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`;
  }
  const xref = new TextEncoder().encode(output).length;
  output += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i < offsets.length; i++) output += String(offsets[i]).padStart(10, '0') + ' 00000 n \n';
  output += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  const blob = new Blob([new TextEncoder().encode(output)], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `Navstar-Receipt-${enc(data.serial).replace(/[^a-zA-Z0-9_-]/g, '-')}.pdf`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 30000);
}
